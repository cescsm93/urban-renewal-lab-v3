-- Additive platform tables. Existing renewal.layers/features are left untouched.
CREATE SCHEMA IF NOT EXISTS renewal;

CREATE TABLE IF NOT EXISTS renewal.app_users (
  username text PRIMARY KEY,
  salt text NOT NULL,
  password_hash text NOT NULL,
  disabled boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS renewal.app_sessions (
  token_hash char(64) PRIMARY KEY,
  username text NOT NULL REFERENCES renewal.app_users(username) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz
);
CREATE INDEX IF NOT EXISTS app_sessions_user_idx ON renewal.app_sessions(username, expires_at);

CREATE TABLE IF NOT EXISTS renewal.app_projects (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  version integer NOT NULL DEFAULT 1 CHECK (version > 0),
  payload jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by text NOT NULL REFERENCES renewal.app_users(username)
);
CREATE TABLE IF NOT EXISTS renewal.app_project_members (
  project_id bigint NOT NULL REFERENCES renewal.app_projects(id) ON DELETE CASCADE,
  username text NOT NULL REFERENCES renewal.app_users(username) ON DELETE CASCADE,
  role text NOT NULL CHECK (role IN ('viewer','editor')),
  PRIMARY KEY(project_id, username)
);
CREATE INDEX IF NOT EXISTS app_project_members_user_idx ON renewal.app_project_members(username);

CREATE TABLE IF NOT EXISTS renewal.app_grants (
  username text NOT NULL REFERENCES renewal.app_users(username) ON DELETE CASCADE,
  scope text NOT NULL,
  resource_type text NOT NULL DEFAULT '*',
  resource_id text NOT NULL DEFAULT '*',
  granted_by text NOT NULL REFERENCES renewal.app_users(username),
  granted_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(username, scope, resource_type, resource_id)
);
